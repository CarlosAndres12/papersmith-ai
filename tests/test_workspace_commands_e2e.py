class LiveSmokeScriptTests(unittest.TestCase):
    """The opt-in live smoke is a contract of this series, not a suggestion."""

    SCRIPT = REPO_ROOT / "scripts" / "cli-paper-live-smoke.sh"

    def test_script_exists_executable_and_covers_every_command(self) -> None:
        self.assertTrue(self.SCRIPT.is_file(), "missing scripts/cli-paper-live-smoke.sh")
        self.assertTrue(os.access(self.SCRIPT, os.X_OK), "live smoke must be executable")
        text = self.SCRIPT.read_text(encoding="utf-8")
        for command in COMMANDS:
            self.assertIn(command, text, f"live smoke must cover {command}")
        self.assertIn("PAPERSMITH_LIVE", text, "live smoke must be explicitly opt-in")

    def test_script_refuses_to_run_without_opt_in(self) -> None:
        env = {key: value for key, value in os.environ.items() if key != "PAPERSMITH_LIVE"}
        completed = subprocess.run(
            ["bash", str(self.SCRIPT), str(new_tmp(self))],
            capture_output=True, text=True, timeout=60, env=env,
        )
        self.assertNotEqual(completed.returncode, 0, "live smoke ran without PAPERSMITH_LIVE")
        self.assertIn("PAPERSMITH_LIVE", completed.stderr + completed.stdout)

    def test_hermetic_smoke_wrapper_still_exists(self) -> None:
        hermetic = REPO_ROOT / "scripts" / "cli-paper-smoke.sh"
        self.assertTrue(hermetic.is_file())
        self.assertTrue(os.access(hermetic, os.X_OK))


