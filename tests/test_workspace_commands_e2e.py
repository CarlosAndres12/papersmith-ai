"""From-scratch command series: every ``papersmith`` command over a CLI-made workspace.

Layer purpose. The paper journey (``test_cli_paper_e2e.py``) walks the research
flow once; this module proves the other half of the product claim: that a
workspace generated by ``papersmith init`` is a working instrument for *every*
command the CLI advertises, including the ones the journey never touches
(``upgrade``, ``target``). Deep engine legs stay in their own suites; every
test here starts from ``init`` and drives the CLI as a user would.

Boundaries stay hermetic: stubbed ingest, symlinked ``node_modules``, dry-run
dispatch, no network, no model calls, no live Kaggle.
"""

