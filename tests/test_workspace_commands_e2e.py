class RunCommandTests(unittest.TestCase):

    def test_run_dry_run_records_a_row_without_dispatching(self) -> None:
        workspace = make_workspace(new_tmp(self))
        dispatched = False

        def _fail_if_dispatched(*args, **kwargs):
            nonlocal dispatched
            dispatched = True
            raise AssertionError("dry-run dispatched a subprocess")

        with mock.patch("papersmith.core.executor.subprocess.run",
                        side_effect=_fail_if_dispatched):
            rc, out, err = capture(["run", "smoke_and_invariants", "--dry-run", str(workspace)])
        self.assertEqual(rc, SUCCESS)
        self.assertFalse(dispatched)
        self.assertIn("dry-run: no job was dispatched", err)
        payload = json.loads(out)
        self.assertTrue(payload["jobs"][0]["dry_run"])
        self.assertTrue(run_ledger.read(workspace)[0]["dry_run"])


